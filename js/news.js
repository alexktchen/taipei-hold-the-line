function bag(make, size) { let q = []; return () => { if (!q.length) { const seen = new Set(); const out = []; for (let i = 0; i < size * 6 && out.length < size; i++) { const s = make(); if (!seen.has(s)) { seen.add(s); out.push(s); } } q = out.sort(() => Math.random() - 0.5); } return q.shift(); }; }
